package coverage

import (
	"os"
	"path/filepath"
	"testing"
)

func writeFile(t *testing.T, dir, name, content string) {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

func TestScanSkipsGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "gen.go", `// Code generated by test. DO NOT EDIT.
package pkg

func ExportedInGenerated() {}
`)
	writeFile(t, dir, "hand.go", `package pkg

// ExportedHandWritten is a hand-written extension.
func ExportedHandWritten() {}

func unexportedHelper() {}

type Widget struct{}

func (w *Widget) Do() {}

func (w *Widget) do() {}

type unexportedType struct{}

func (u unexportedType) Exported() {}
`)
	writeFile(t, dir, "hand_test.go", `package pkg

func ExportedButATestFile() {}
`)

	symbols, err := Scan(dir)
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}

	got := make(map[string]Symbol, len(symbols))
	for _, s := range symbols {
		got[s.Key()] = s
	}

	if _, ok := got[".#ExportedInGenerated"]; ok {
		t.Error("expected generated file's symbol to be excluded")
	}
	if _, ok := got[".#ExportedButATestFile"]; ok {
		t.Error("expected _test.go file's symbol to be excluded")
	}
	if _, ok := got[".#unexportedHelper"]; ok {
		t.Error("expected unexported func to be excluded")
	}
	if s, ok := got[".#ExportedHandWritten"]; !ok || s.Kind != "func" {
		t.Errorf("expected hand-written exported func to be found, got %+v ok=%v", s, ok)
	}
	if s, ok := got[".#(Widget).Do"]; !ok || s.Kind != "method" {
		t.Errorf("expected exported method on exported receiver to be found, got %+v ok=%v", s, ok)
	}
	if _, ok := got[".#(Widget).do"]; ok {
		t.Error("expected unexported method to be excluded")
	}
	if _, ok := got[".#(unexportedType).Exported"]; ok {
		t.Error("expected exported method on unexported receiver type to be excluded")
	}
	if s, ok := got[".#Widget"]; !ok || s.Kind != "type" {
		t.Errorf("expected exported type to be found, got %+v ok=%v", s, ok)
	}
}

func TestScanPrefersExtensionsManifest(t *testing.T) {
	dir := t.TempDir()
	// A root-package .go file that, if AST-scanned, would report a
	// different symbol than the manifest. Presence of the manifest should
	// make Scan trust it instead of parsing this file for the root package.
	writeFile(t, dir, "hand.go", `package pkg

func FromAST() {}
`)
	writeFile(t, dir, "client_extensions_manifest.json", `{
  "formatVersion": 1,
  "package": "flexera",
  "files": [
    {
      "path": "hand.go",
      "declarations": [
        {"name": "FromManifest", "kind": "func"},
        {"name": "MaxZone", "kind": "const"},
        {"name": "APIBaseURL", "kind": "method", "receiver": "AuthHelper"}
      ]
    }
  ]
}`)
	// Sub-packages have no manifest coverage upstream, so they must still
	// be AST-scanned even when the root manifest is present.
	writeFile(t, dir, "service/thing/v1/thing.go", `package v1

func Thing() {}

const (
	ExportedConst = "const"
	unexportedConst = "unexported"
)

var (
	ExportedVar = "var"
	unexportedVar = "unexported"
)
`)

	symbols, err := Scan(dir)
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}
	got := make(map[string]Symbol, len(symbols))
	for _, s := range symbols {
		got[s.Key()] = s
	}

	if _, ok := got[".#FromAST"]; ok {
		t.Error("expected root-package file to not be AST-scanned when a manifest is present")
	}
	if _, ok := got[".#FromManifest"]; !ok {
		t.Error("expected manifest-reported func to be found")
	}
	if s, ok := got[".#MaxZone"]; !ok || s.Kind != "const" {
		t.Errorf("expected manifest-reported const to be found, got %+v ok=%v", s, ok)
	}
	if s, ok := got[".#(AuthHelper).APIBaseURL"]; !ok || s.Kind != "method" {
		t.Errorf("expected manifest-reported method to be found, got %+v ok=%v", s, ok)
	}
	if _, ok := got["service/thing/v1#Thing"]; !ok {
		t.Error("expected sub-package symbol to still be AST-scanned")
	}
	if s, ok := got["service/thing/v1#ExportedConst"]; !ok || s.Kind != "const" {
		t.Errorf("expected exported sub-package const to be found, got %+v ok=%v", s, ok)
	}
	if s, ok := got["service/thing/v1#ExportedVar"]; !ok || s.Kind != "var" {
		t.Errorf("expected exported sub-package var to be found, got %+v ok=%v", s, ok)
	}
	if _, ok := got["service/thing/v1#unexportedConst"]; ok {
		t.Error("expected unexported sub-package const to be excluded")
	}
	if _, ok := got["service/thing/v1#unexportedVar"]; ok {
		t.Error("expected unexported sub-package var to be excluded")
	}
}

func TestScanSkipsCmdSubdirectory(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "cmd/tool/main.go", `package main

func ExportedInCmd() {}
`)
	symbols, err := Scan(dir)
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}
	for _, s := range symbols {
		if s.Name == "ExportedInCmd" {
			t.Fatalf("expected cmd/ subdirectory to be skipped, found %+v", s)
		}
	}
}

func TestScanPackagePaths(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "root.go", `package pkg

func Root() {}
`)
	writeFile(t, dir, "service/thing/v1/thing.go", `package v1

func Thing() {}
`)
	symbols, err := Scan(dir)
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}
	byKey := make(map[string]Symbol, len(symbols))
	for _, s := range symbols {
		byKey[s.Key()] = s
	}
	if _, ok := byKey[".#Root"]; !ok {
		t.Error("expected root package symbol keyed with '.'")
	}
	if _, ok := byKey["service/thing/v1#Thing"]; !ok {
		t.Error("expected nested package symbol keyed with its relative import path")
	}
}

func TestDiffAgainstAllowlist(t *testing.T) {
	found := []Symbol{
		{Package: ".", Name: "Covered", Kind: "func"},
		{Package: ".", Name: "New", Kind: "func"},
	}
	allow := Allowlist{
		".#Covered": {Symbol: ".#Covered", Status: "covered", Command: "foo bar"},
		".#Gone":    {Symbol: ".#Gone", Status: "excluded", Reason: "removed upstream"},
	}
	diff := DiffAgainstAllowlist(found, allow)
	if len(diff.New) != 1 || diff.New[0].Name != "New" {
		t.Errorf("expected exactly one new symbol (New), got %+v", diff.New)
	}
	if len(diff.Stale) != 1 || diff.Stale[0].Symbol != ".#Gone" {
		t.Errorf("expected exactly one stale entry (.#Gone), got %+v", diff.Stale)
	}
}

func TestLoadAllowlistValidation(t *testing.T) {
	dir := t.TempDir()

	cases := []struct {
		name    string
		json    string
		wantErr bool
	}{
		{"valid covered", `[{"symbol":"a","status":"covered","command":"x"}]`, false},
		{"valid excluded", `[{"symbol":"a","status":"excluded","reason":"x"}]`, false},
		{"covered missing command", `[{"symbol":"a","status":"covered"}]`, true},
		{"excluded missing reason", `[{"symbol":"a","status":"excluded"}]`, true},
		{"invalid status", `[{"symbol":"a","status":"maybe"}]`, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(dir, tc.name+".json")
			if err := os.WriteFile(path, []byte(tc.json), 0o644); err != nil {
				t.Fatalf("write: %v", err)
			}
			_, err := LoadAllowlist(path)
			if (err != nil) != tc.wantErr {
				t.Errorf("LoadAllowlist(%q) error=%v, wantErr=%v", tc.json, err, tc.wantErr)
			}
		})
	}
}
